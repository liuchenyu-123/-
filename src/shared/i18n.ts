/**
 * UI language packs for the React side (pages + client components).
 *
 * Both packs deliberately share the exact same key shape so `ui(lang)` is fully
 * typed: a missing key in either language is a TypeScript error, not a runtime blank.
 * Engine-side strings live in engine-lang.mjs because that module must stay pure ESM.
 */

export type Lang = 'zh' | 'en';

export const DEFAULT_LANG: Lang = 'zh';

export function resolveLang(value: unknown): Lang {
  return value === 'en' ? 'en' : 'zh';
}

/** Replace {name} placeholders in a translated string. */
export function fill(
  template: string,
  vars: Record<string, string | number | null | undefined>,
): string {
  return Object.entries(vars).reduce(
    (acc, [key, value]) => acc.split(`{${key}}`).join(value == null ? '—' : String(value)),
    template,
  );
}

