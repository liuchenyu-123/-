/**
 * Deterministically generate the sample sales history shipped with the project.
 *
 * The data is produced from an explicit demand model (baseline demand + price
 * elasticity + weather/day effects + bounded noise). That is deliberate: the
 * pricing engine fits elasticity back out of these rows, so a unit test can
 * verify the fit instead of comparing against a hard-coded "right answer".
 *
 * Run: npm run generate:data
 * Writes:
 *   src/shared/sample-sales.mjs          (in-browser / server-side inline copy)
 *   public/data/sample-sales-history.csv (downloadable from the UI)
 *   data/sample-sales-history.csv        (standalone deliverable)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const SKUS = [
  { id: 'yogurt', name: '原味酸奶杯', nameEn: 'Plain yogurt cups', category: 'dairy', unit: 'cup', unitKg: 0.15, unitCost: 2.2, listPrice: 4.5, baseDemand: 10, elasticity: 2.0, received: 36, expiryDays: 1 },
  { id: 'greens', name: '本地叶菜', nameEn: 'Leafy greens', category: 'veg', unit: 'bunch', unitKg: 0.30, unitCost: 1.8, listPrice: 3.8, baseDemand: 8, elasticity: 1.6, received: 28, expiryDays: 2 },
  { id: 'toast', name: '全麦吐司', nameEn: 'Whole-wheat toast', category: 'bakery', unit: 'loaf', unitKg: 0.40, unitCost: 4.5, listPrice: 9.0, baseDemand: 6, elasticity: 1.2, received: 20, expiryDays: 2 },
  { id: 'meal', name: '熟食盒饭', nameEn: 'Ready-meal boxes', category: 'prepared', unit: 'box', unitKg: 0.35, unitCost: 6.0, listPrice: 12.0, baseDemand: 8, elasticity: 2.1, received: 26, expiryDays: 1 },
  { id: 'mango', name: '芒果', nameEn: 'Mangoes', category: 'fruit', unit: 'pc', unitKg: 0.25, unitCost: 3.0, listPrice: 6.0, baseDemand: 9, elasticity: 1.5, received: 30, expiryDays: 3 },
  { id: 'milk', name: '鲜牛奶', nameEn: 'Fresh milk', category: 'dairy', unit: 'bottle', unitKg: 0.50, unitCost: 3.5, listPrice: 7.0, baseDemand: 8, elasticity: 1.8, received: 24, expiryDays: 2 },
];

const DISCOUNTS = [0, 10, 0, 20, 30, 0, 10, 40, 0, 20, 30, 0, 15, 25];
const WEATHER = ['normal', 'normal', 'heat', 'normal', 'rain', 'normal', 'normal', 'heat', 'normal', 'rain', 'normal', 'normal', 'heat', 'normal'];
const WEATHER_FACTOR = { normal: 1, heat: 0.92, rain: 0.80 };
const DAY_FACTOR = { weekday: 1, weekend: 1.12, holiday: 0.88 };

/** Small deterministic LCG so every run produces byte-identical data. */
let seed = 20261108;
function rand() {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 0x100000000;
}

const HEADER = [
  'date', 'sku_id', 'sku_name', 'sku_name_en', 'category', 'unit',
  'unit_kg', 'unit_cost', 'list_price', 'selling_price',
  'qty_received', 'qty_sold', 'qty_wasted', 'weather', 'day_type', 'expiry_days',
];

const rows = [];
for (let day = 0; day < 14; day += 1) {
  const date = new Date(Date.UTC(2026, 9, 26 + day));
  const iso = date.toISOString().slice(0, 10);
  const dow = date.getUTCDay();
  const dayType = iso === '2026-11-07' ? 'holiday' : (dow === 0 || dow === 6 ? 'weekend' : 'weekday');
  const weather = WEATHER[day];

  SKUS.forEach((sku, si) => {
    const discount = DISCOUNTS[(day + si * 3) % DISCOUNTS.length];
    const price = sku.listPrice * (1 - discount / 100);
    const ratio = price / sku.listPrice;
    const noise = 1 + (rand() - 0.5) * 0.14;
    const demand = sku.baseDemand * Math.pow(ratio, -sku.elasticity)
      * WEATHER_FACTOR[weather] * DAY_FACTOR[dayType] * noise;
    const sold = Math.max(0, Math.min(sku.received, Math.round(demand)));
    const leftover = sku.received - sold;
    // Items with more than one day left can be carried over to tomorrow.
    const carry = sku.expiryDays >= 2 ? Math.floor(leftover * 0.4) : 0;
    const wasted = Math.max(0, leftover - carry);
    rows.push([
      iso, sku.id, sku.name, sku.nameEn, sku.category, sku.unit,
      sku.unitKg.toFixed(2), sku.unitCost.toFixed(2), sku.listPrice.toFixed(2),
      price.toFixed(2), sku.received, sold, wasted, weather, dayType, sku.expiryDays,
    ]);
  });
}

const csv = [HEADER.join(','), ...rows.map((r) => r.join(','))].join('\n') + '\n';

const meta = {
  rows: rows.length,
  skus: SKUS.length,
  days: 14,
  from: rows[0][0],
  to: rows[rows.length - 1][0],
  city: 'guangzhou',
  note: 'Deterministic sample data generated from an explicit demand model; not real transactions.',
};

const moduleSource = `/**
 * AUTO-GENERATED by scripts/generate-sample-sales.mjs - do not edit by hand.
 * Inlined so the pricing page can load the sample dataset without a network request.
 */
export const SAMPLE_SALES_META = Object.freeze(${JSON.stringify(meta, null, 2)});

export const SAMPLE_SALES_CSV = ${JSON.stringify(csv)};
`;

mkdirSync(path.join(root, 'public/data'), { recursive: true });
mkdirSync(path.join(root, 'data'), { recursive: true });
writeFileSync(path.join(root, 'src/shared/sample-sales.mjs'), moduleSource, 'utf8');
writeFileSync(path.join(root, 'public/data/sample-sales-history.csv'), '\uFEFF' + csv, 'utf8');
writeFileSync(path.join(root, 'data/sample-sales-history.csv'), '\uFEFF' + csv, 'utf8');

console.log(`Generated ${meta.rows} rows / ${meta.skus} SKUs / ${meta.days} days (${meta.from} → ${meta.to})`);
console.log('  src/shared/sample-sales.mjs');
console.log('  public/data/sample-sales-history.csv');
console.log('  data/sample-sales-history.csv');
